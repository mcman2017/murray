def main_ext() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for name, make in [("clipped.png", clipped), ("clean_soft.png", clean_soft),
                       ("sketch_parabola2.png", sketch_parabola2), ("cascade_injected.png", cascade_injected)]:
        img = make()
        img.save(OUT / name, format="PNG")
        print(name, img.size)


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
