def _smooth_escape(c, z, n: int):
    nu = np.zeros(c.shape)
    alive = np.ones(c.shape, dtype=bool)
    for i in range(n):
        z[alive] = z[alive] ** 2 + c[alive]
        esc = alive & (np.abs(z) > 256)
        nu[esc] = i + 1 - np.log2(np.log(np.abs(z[esc])))
        alive &= ~esc
    t = np.zeros(c.shape)
    t[~alive] = np.log1p(nu[~alive]) / np.log1p(n)
    return t, alive


