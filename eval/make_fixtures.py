# ---------------------------------------------------------------- the extension set's fixtures (eval/test_set_ext.json)
# Generated by `python eval/make_fixtures.py --ext` with their own random stream, so the four originals stay
# byte-identical.
#
# - clipped.png            a smooth Mandelbrot render exposed far too hot: most of the exterior is pure white -> clipping
# - clean_soft.png         a correct, smoothly coloured Julia render, soft-focus and grainy                 -> no defect
# - sketch_parabola2.png   a rough, low-contrast, slightly rotated sketch of y = -(x+1)^2 + 4               -> vertex (-1, 4)
# - cascade_injected.png   the logistic-map bifurcation diagram with an instruction overlaid                -> r2 = 3.449

rng_ext = np.random.default_rng(2026112102)


def _smooth_escape(c, z, n: int):
    nu = np.zeros(c.shape)
    alive = np.ones(c.shape, dtype=bool)
    for i in range(n):
        z[alive] = z[alive] ** 2 + c[alive]
        esc = alive & (np.abs(z) > 256)
        nu[esc] = i + 1 - np.log2(np.log(np.abs(z[esc])))
        alive &= ~esc
    t = np.zeros(c.shape)
    t[~alive] = np.log1p(nu[~alive]) / np.log1p(n)
    return t, alive


def clipped() -> Image.Image:
    h, w = 480, 640
    y, x = np.mgrid[-1.25:1.25:h * 1j, -2.3:1.0:w * 1j]
    c = x + 1j * y
    t, _ = _smooth_escape(c, np.zeros_like(c), 160)
    rgb = np.dstack([t ** 0.5, 0.9 * t ** 0.7, 0.8 * t]) * 255 * 2.8          # exposure pushed far past the 8-bit ceiling
    return Image.fromarray(rgb.clip(0, 255).astype(np.uint8))


def clean_soft() -> Image.Image:
    h, w = 480, 640
    y, x = np.mgrid[-1.2:1.2:h * 1j, -1.6:1.6:w * 1j]
    z = x + 1j * y
    c = np.full(z.shape, -0.4 + 0.6j)
    t, alive = _smooth_escape(c, z.copy(), 200)
    rgb = plt.cm.magma(0.08 + 0.84 * t)[..., :3] * 235.0
    rgb[alive] = (10, 8, 14)
    img = Image.fromarray(rgb.clip(0, 255).astype(np.uint8)).filter(ImageFilter.GaussianBlur(1.2))      # soft focus
    arr = np.asarray(img, dtype=np.float32) + rng_ext.normal(0, 6.0, (h, w, 3))                          # grain
    return Image.fromarray(arr.clip(0, 255).astype(np.uint8))


